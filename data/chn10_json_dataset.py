# %% Imports

# Standard imports
import json
from pathlib import Path
import numpy as np

# From other libraries
from PIL import Image
import torch
from torch.utils.data import Dataset, DataLoader
from torchvision.transforms import v2

# %%

class CHN10SegmentationDataset(Dataset):
    """
    PyTorch Dataset for CHN10-CUG Semantic Segmentation (Domain Adaptation).
    Handles loading images and masks with proper naming conventions (_sat.jpg -> _mask.png).
    """
    def __init__(self, json_split_path: str, domain_key: str = "source_domain", 
                 split: str = "train", transform=None):
        """
        Args:
            json_split_path (str): Path to the dataset_splits.json file generated by CHN10DomainManager.
            domain (str): Either "source_domain" or "target_domain".
            split (str): One of "train", "val", or "test".
            transform: Optional transform/augmentation pipeline (e.g., Albumentations).
        """
        self.split = split
        self.domain_key = domain_key
        self.transform = transform
        
        # Load paths from the JSON configuration
        with open(json_split_path, "r", encoding="utf-8") as f:
            splits_data = json.load(f)
            
        # Raise error if domain is not a key in json dataset
        if domain_key not in splits_data:
            raise KeyError(f"Domain '{domain_key}' not found in split file"
                           f". Available: {list(splits_data.keys())}")
        
        self.image_paths = splits_data[domain_key][split]

    def __len__(self) -> int:
        return len(self.image_paths)
    
    def _get_gt_path(self, img_path_str: str) -> Path:
        """Maps an image path (.../images/am100001_sat.jpg) to its mask path (.../gt/am100001_mask.png)."""
        img_p = Path(img_path_str)
        parts = list(img_p.parts)
        
        # Replaces the "images" by "gt" in the path 
        if "images" in parts:
            parts[parts.index("images")] = "gt"
        else:
            raise ValueError(f"Path does not contain an 'images' directory: {img_p}")
        
        # Replaces "_sat.jpg" by "_mask.png"
        gt_dir = Path(*parts[:-1])
        base_name = img_p.stem[:-4] if img_p.stem.endswith("_sat") else img_p.stem
        
        gt_path = gt_dir / f"{base_name}_mask.png"
        if not gt_path.exists():
            raise FileNotFoundError(f"Ground Truth mask not found at: {gt_path}")
        
        return gt_path
    
    def __getitem__(self, idx: int) -> dict:
        # 1. Load image and mask
        img_path = self.image_paths[idx]
        image = Image.open(img_path).convert("RGB")
        
        gt_path = self._get_gt_path(img_path)
        mask = Image.open(gt_path).convert("L")
        
        # 2. Convert mask to binary array (0 or 1)
        mask_np = (np.array(mask) > 0).astype(np.uint8) # Binary mask (0 or 1)
        
        # 3. Convert to Tensors using torchvision.transforms.v2 functional tools
        image_tensor = v2.functional.to_image(image)  # Converts to CHN tensor [0, 255] uint8
        image_tensor = v2.functional.to_dtype(image_tensor, dtype=torch.float32, scale=True)  # Normalizes to [0, 1] float32
        
        mask_tensor = torch.tensor(mask_np, dtype=torch.long)
        
        # 4. Apply torchvision v2 augmentations (transforms both image and mask synchronously)
        if self.transform is not None:
            image_tensor, mask_tensor = self.transform(image_tensor, mask_tensor)
            
        return {
            "image": image_tensor,
            "mask": mask_tensor,
            "image_path": img_path
        }

        
